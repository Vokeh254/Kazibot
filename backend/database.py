"""
Async database engine and session factory for KaziBot.

Reads DATABASE_URL from the application settings and creates:
  - An async SQLAlchemy engine (aiosqlite for SQLite, asyncpg for PostgreSQL)
  - An async session factory via async_sessionmaker
  - A FastAPI dependency `get_async_session` for use in route handlers
"""

from collections.abc import AsyncGenerator

from sqlalchemy.ext.asyncio import (
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)
from sqlalchemy.orm import DeclarativeBase

from backend.config import settings


class Base(DeclarativeBase):
    """Shared declarative base for all ORM models.

    Importing this from database.py ensures that all model classes share the
    same metadata object, which Alembic needs for autogenerated migrations.
    """

    pass


# ── Engine ────────────────────────────────────────────────────────────────────

def _build_engine_kwargs(database_url: str) -> dict:
    """Return engine kwargs appropriate for the chosen database backend."""
    kwargs: dict = {}
    if database_url.startswith("sqlite"):
        # aiosqlite requires `check_same_thread=False` under the hood; the
        # connect_args key is passed through to sqlite3 via aiosqlite.
        kwargs["connect_args"] = {"check_same_thread": False}
    return kwargs


engine = create_async_engine(
    settings.DATABASE_URL,
    echo=False,  # Set to True for SQL query logging during development
    **_build_engine_kwargs(settings.DATABASE_URL),
)

# ── Session factory ───────────────────────────────────────────────────────────

AsyncSessionFactory: async_sessionmaker[AsyncSession] = async_sessionmaker(
    bind=engine,
    class_=AsyncSession,
    expire_on_commit=False,  # Keep loaded attributes usable after commit
)

# ── FastAPI dependency ────────────────────────────────────────────────────────


async def get_async_session() -> AsyncGenerator[AsyncSession, None]:
    """Yield an async database session as a FastAPI dependency.

    Usage in a route handler::

        from fastapi import Depends
        from sqlalchemy.ext.asyncio import AsyncSession
        from backend.database import get_async_session

        @router.get("/items")
        async def list_items(session: AsyncSession = Depends(get_async_session)):
            ...

    The session is automatically closed (and any open transaction rolled back
    on error) when the route handler returns.
    """
    async with AsyncSessionFactory() as session:
        try:
            yield session
        except Exception:
            await session.rollback()
            raise
        finally:
            await session.close()
